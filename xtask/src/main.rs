//! Project tasks: `cargo xtask <command>`.
#![allow(clippy::print_stdout, clippy::print_stderr)]

use std::fs::File;
use std::io::{BufWriter, Write};
use std::path::PathBuf;

use clap::{Parser, Subcommand};

mod package;

#[derive(Parser)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Write a synthetic XML file of roughly the given size for benchmarks.
    GenFixture {
        /// Target size in MiB.
        #[arg(long, default_value_t = 100)]
        mib: u64,
        #[arg(long, default_value = "fixtures/orders.xml")]
        out: PathBuf,
    },
    /// Build the Linux .deb and .rpm into target/dist (PKG-30, PKG-31). Needs cargo-zigbuild,
    /// zig and dpkg-deb.
    Package {
        /// Use the executables already in target/x86_64-unknown-linux-gnu/release.
        #[arg(long)]
        skip_build: bool,
    },
}

fn main() -> anyhow::Result<()> {
    match Cli::parse().command {
        Command::GenFixture { mib, out } => gen_fixture(mib, &out),
        Command::Package { skip_build } => {
            let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .parent()
                .expect("xtask is in the workspace");
            package::package(root, skip_build)
        }
    }
}

/// Orders with customers, line items, attributes, entities, comments and CDATA, so the
/// benchmark exercises every node kind rather than one repeated tag.
fn gen_fixture(mib: u64, out: &PathBuf) -> anyhow::Result<()> {
    let target = mib * 1024 * 1024;
    if let Some(dir) = out.parent() {
        std::fs::create_dir_all(dir)?;
    }
    let mut w = BufWriter::with_capacity(1 << 20, File::create(out)?);
    let mut written = 0u64;
    let mut put = |w: &mut BufWriter<File>, s: &str| -> std::io::Result<()> {
        written += s.len() as u64;
        w.write_all(s.as_bytes())
    };
    put(
        &mut w,
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- generated by cargo xtask gen-fixture -->\n<orders>\n",
    )?;
    let mut seed = 0x2545_F491_4F6C_DD1Du64;
    let mut rnd = move || {
        seed ^= seed << 13;
        seed ^= seed >> 7;
        seed ^= seed << 17;
        seed
    };
    let mut id = 0u64;
    let mut size = 0u64;
    while size < target {
        id += 1;
        let items = 1 + rnd() % 5;
        let mut s = format!(
            "  <order id=\"{id}\" date=\"2026-{:02}-{:02}\" status=\"{}\">\n    <customer ref=\"C{}\">\n      <name>Customer {} &amp; Sons</name>\n      <email>c{}@example.com</email>\n    </customer>\n    <items>\n",
            1 + rnd() % 12,
            1 + rnd() % 28,
            ["open", "shipped", "closed"][(rnd() % 3) as usize],
            rnd() % 100_000,
            rnd() % 100_000,
            rnd() % 100_000,
        );
        for n in 0..items {
            s.push_str(&format!(
                "      <item line=\"{}\" sku=\"SKU-{:06}\" qty=\"{}\"><price currency=\"EUR\">{}.{:02}</price></item>\n",
                n + 1,
                rnd() % 1_000_000,
                1 + rnd() % 9,
                rnd() % 500,
                rnd() % 100
            ));
        }
        s.push_str("    </items>\n");
        if id.is_multiple_of(10) {
            s.push_str("    <note><![CDATA[Fragile: handle with <care> & attention]]></note>\n");
        }
        s.push_str("  </order>\n");
        put(&mut w, &s)?;
        size += s.len() as u64;
    }
    put(&mut w, "</orders>\n")?;
    w.flush()?;
    println!(
        "wrote {} orders, {:.1} MiB to {}",
        id,
        written as f64 / 1048576.0,
        out.display()
    );
    Ok(())
}
